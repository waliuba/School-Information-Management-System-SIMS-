-- Run once against an existing Oracle database before using attendance.
CREATE TABLE attendance (
    attendance_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id NUMBER(19) NOT NULL,
    attendance_date DATE NOT NULL,
    status VARCHAR2(20) NOT NULL,
    remarks VARCHAR2(255),
    CONSTRAINT fk_attendance_student
        FOREIGN KEY (student_id) REFERENCES students(student_id)
);

CREATE INDEX idx_attendance_student_date
    ON attendance (student_id, attendance_date);
