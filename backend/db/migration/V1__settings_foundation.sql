-- Phase 1 additive Oracle migration. 
ALTER TABLE USERS ADD (TOKEN_VERSION NUMBER(10) DEFAULT 0 NOT NULL);

CREATE TABLE SIMS_SETTING (
    SETTING_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SETTING_SCOPE VARCHAR2(20 CHAR) NOT NULL,
    OWNER_ID NUMBER(19) NOT NULL,
    SETTING_KEY VARCHAR2(80 CHAR) NOT NULL,
    SETTING_VALUE VARCHAR2(1000 CHAR) NOT NULL,
    SETTING_VERSION NUMBER(19) DEFAULT 0 NOT NULL,
    CONSTRAINT UK_SIMS_SETTING_SCOPE_KEY UNIQUE (SETTING_SCOPE, OWNER_ID, SETTING_KEY),
    CONSTRAINT CK_SIMS_SETTING_SCOPE CHECK (SETTING_SCOPE IN ('USER', 'SCHOOL', 'SYSTEM'))
);

CREATE TABLE SIMS_AUDIT_EVENT (
    EVENT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ACTOR VARCHAR2(100 CHAR) NOT NULL,
    ACTION VARCHAR2(80 CHAR) NOT NULL,
    TARGET VARCHAR2(160 CHAR) NOT NULL,
    CORRELATION_ID VARCHAR2(64 CHAR) NOT NULL,
    OCCURRED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    DETAILS CLOB
);

CREATE INDEX IX_SIMS_AUDIT_OCCURRED ON SIMS_AUDIT_EVENT (OCCURRED_AT);
CREATE INDEX IX_SIMS_AUDIT_ACTOR ON SIMS_AUDIT_EVENT (ACTOR, OCCURRED_AT);

CREATE OR REPLACE TRIGGER TRG_SIMS_AUDIT_IMMUTABLE
BEFORE UPDATE OR DELETE ON SIMS_AUDIT_EVENT
BEGIN
    RAISE_APPLICATION_ERROR(-20001, 'SIMS audit events are append-only');
END;
